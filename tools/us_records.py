#!/usr/bin/env python3
"""The registry claims that make machines 35..39 the user slots U1..U5 (0021-ext; rytm-teensy
docs/superpowers/specs/2026-10-10-user-slots-rytm-design.md 1.1, 1.5), as TOML on stdout:

    .venv/bin/python tools/us_records.py > /tmp/us_claims.toml

Every `expect` is read from the stock image (build/stock_mainos.bin, `make build` makes it) and every
value the spec states is checked against it first (engine entries, name pointers, SRC pages, the
records' machine fields), so a different image stops here rather than producing claims. Nothing of
the image is written anywhere but the claims' expect fields, as for every other claim in the registry.

Per machine m = 35..39 (slot s = m - 35): the engine entry (0x4029037c + 4 m) -> ext_render; home and
mask ffff (one 10-byte patch for all five at 0x401bf1c2); the long and short name pointers
(0x401befa4 + 8 m) -> us_l<n> / us_s<n> (RAM buffers in .usr); the SRC page's 8 records
(0x40287cc8 + 36 m + 4) -> 334 + 8 s .. + 7 in order; the 8 records' first 40 bytes
(0x401bf918 + 0x34 r): slot 9 + k, range 0..127, default 64, CC 16 + k, NRPN 1:k (0x80 + k), the rest
as stock (+0 keeps the machine m: the setter's and the flush's kind gate, research R11). Page 2's shared
records 438 457 458 459 460 403 404 405: machine 0x36, slot 17 + j, range 0..127, default 64, no CC/NRPN,
+32 0x32 + j, +36 0x600 (0021's page-2 pattern, record 422; kind 0x36 >= 53 passes R11's gate, where
stock's 48, 52 and 43 do not). Where stock already holds the bytes (records 341, 346, 364) the claim
is a guard (`guard = true`, replace == expect): it changes nothing, and another mod's patch there
collides in layout.py.
"""
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = 0x40000400
ENGINES = {35: 0x4010f990, 36: 0x4010ee08, 37: 0x40116e58, 38: 0x4011657c, 39: 0x401157d8}
NAMES = {35: (0x401bf0bc, 0x401bf0c0), 36: (0x401bf0c4, 0x401bf0c8), 37: (0x401bf0cc, 0x401bf0d0),
         38: (0x401bf0d4, 0x401bf0d8), 39: (0x401bf0dc, 0x401bf0e0)}
SRC = {35: [334, 338, 339, 337, 340, 336, 341, 335], 36: [342, 346, 347, 345, 348, 344, 349, 343],
       37: [356, 357, 350, 351, 353, 354, 355, 352], 38: [358, 360, 359, 361, 363, 362, 364, 365],
       39: [372, 373, 366, 367, 371, 369, 370, 368]}
P2 = [438, 457, 458, 459, 460, 403, 404, 405]


def rec_addr(r):
    return 0x401bf918 + 0x34 * r


def main():
    img = open(os.path.join(ROOT, "build", "stock_mainos.bin"), "rb").read()
    rd = lambda a, n: img[a - BASE:a - BASE + n]
    u32 = lambda a: struct.unpack(">I", rd(a, 4))[0]
    out = ["# ---- 0021-ext: user slots U1..U5 = machines 35..39 (generated by tools/us_records.py) ----"]

    def patch(addr, size, expect, note, replace=None, sym=None):
        out.append("[[patch]]")
        out.append('owner       = "0021-ext"')
        out.append(f"addr        = 0x{addr:08x}")
        out.append(f"size        = {size}")
        out.append(f'expect      = "{expect.hex()}"')
        out.append(f'from_symbol = "{sym}"' if sym else f'replace     = "{replace.hex()}"')
        if replace is not None and replace == expect:   # stock already holds it: a guard (layout.py), not a patch
            out.append("guard       = true")
            note += " - stock already holds it: a guard, so another mod's patch here collides"
        out.append(f'note        = "{note}"')
        out.append("")

    for m in range(35, 40):
        s = m - 35
        a = 0x4029037c + 4 * m
        if u32(a) != ENGINES[m]:
            sys.exit(f"engine entry of {m} at {a:#x} is {u32(a):#x}, not {ENGINES[m]:#x}: another image")
        patch(a, 4, rd(a, 4), f"engine entry of machine {m} (U{s + 1}): ext_render, as machine 44", sym="ext_render")
        for i, sym in enumerate((f"us_l{s + 1}", f"us_s{s + 1}")):
            a = 0x401befa4 + 8 * m + 4 * i
            if a != NAMES[m][i] or not BASE <= u32(a) < BASE + len(img):
                sys.exit(f"name pointer at {a:#x} ({u32(a):#x}) is not a string of the image")
            patch(a, 4, rd(a, 4), f"machine {m} {'long' if not i else 'short'} name: U{s + 1}'s RAM buffer", sym=sym)
        a = 0x40287cc8 + 36 * m + 4
        recs = list(struct.unpack(">8I", rd(a, 32)))
        if recs != SRC[m]:
            sys.exit(f"SRC page of {m} at {a:#x} lists {recs}, not {SRC[m]}")
        first = 334 + 8 * s
        patch(a, 32, rd(a, 32), f"machine {m}'s SRC page: records {first}..{first + 7} in order (U{s + 1}'s P1..P8)",
              replace=struct.pack(">8I", *range(first, first + 8)))
        for k in range(8):
            r = first + k
            st = rd(rec_addr(r), 40)
            if struct.unpack(">I", st[0:4])[0] != m or st[26:28] != b"\xff\xff":
                sys.exit(f"record {r} at {rec_addr(r):#x} is not machine {m}'s CC record ({st.hex()})")
            new = st[0:4] + struct.pack(">IIII", 9 + k, 0, 0x7f00, 0x4000) + st[20:24] + struct.pack(">H", 16 + k) + \
                st[26:28] + struct.pack(">I", 0x80 + k) + st[32:40]
            patch(rec_addr(r), 40, st, f"record {r}: U{s + 1} P{k + 1}, slot {9 + k}, 0..127, default 64, CC {16 + k}, NRPN 1:{k}",
                  replace=new)
    a = 0x401bf17c + 2 * 35
    if rd(a, 10) != bytes(10):
        sys.exit(f"home/mask of 35..39 at {a:#x} is {rd(a, 10).hex()}, not zero")
    patch(a, 10, rd(a, 10), "machines 35..39 (U1..U5): home -1 and every voice, as machine 44", replace=b"\xff" * 10)
    for j, r in enumerate(P2):
        st = rd(rec_addr(r), 40)
        new = struct.pack(">IIIII", 0x36, 17 + j, 0, 0x7f00, 0x4000) + bytes(4) + b"\xff" * 8 + struct.pack(">II", 0x32 + j, 0x600)
        patch(rec_addr(r), 40, st, f"record {r}: the user slots' shared page 2, sample word {17 + j}", replace=new)
    print("\n".join(out))


if __name__ == "__main__":
    main()
