# elekloader (mods/0027-elekloader/design.md). vendor/elekloader is GPL-2.0-or-later
# and is only executed here, like elektron-firmware-tool: nothing of it is copied into
# this repository. The pinned commit is the Makefile's ELEK_REV; build.py refuses another.
ELEK_DIR = ROOT / "vendor" / "elekloader"
ELEK_REV = "8972d70629f230af99c63c8624a886b33ec08299"
ELEK_MOD = "0027-elekloader"
ELEK_CROSS = "m68k-elf-"
ELEK_ID = "rytm-"          # elemod id = this + the mod's id, e.g. rytm-0021-ext


def elek_pinning(meta):
    """Both tools must pin the same stock: elekloader's Rytm 1.73 release (syx and main
    OS sha256, main OS length) has to be ours (stock/SHA256SUMS, re/symbols.toml meta)."""
    if not (ELEK_DIR / ".git").exists():
        raise SystemExit(f"{ELEK_DIR} missing: make setup")
    rev = run(["git", "-C", ELEK_DIR, "rev-parse", "HEAD"]).strip()
    if rev != ELEK_REV:
        raise SystemExit(f"vendor/elekloader is at {rev}, build.py is pinned to {ELEK_REV}")
    sys.path.insert(0, str(ELEK_DIR))
    try:
        from elekloader.devices import analog_rytm_mk2 as prof
    finally:
        sys.path.pop(0)
    rel = prof.DEVICE.releases.get("1.73")
    sums = (ROOT / "stock" / "SHA256SUMS").read_text().split()
    ours = dict(zip(sums[1::2], sums[0::2]))[STOCK_SYX.name]
    for what, theirs, mine in (("stock .syx sha256", rel.syx_sha256, ours),
                               ("MAIN OS sha256", rel.main_sha256, meta["mainos_sha256"]),
                               ("MAIN OS length", rel.main_len, meta["mainos_size"])):
        if theirs != mine:
            raise SystemExit(f"elekloader's Rytm 1.73 {what} is {theirs}, ours {mine}")
    if prof.DEVICE.main_load != meta["base"]:
        raise SystemExit(f"elekloader's load address 0x{prof.DEVICE.main_load:08x} != ours")
    return rev, prof.DEVICE.ddr


def change_runs(a: bytes, b: bytes, base: int, mine=lambda va: True):
    """(addr, stock, new) for each run of differing bytes `mine` accepts (by address),
    joined across gaps of < 4 unchanged bytes."""
    out, i, n = [], 0, len(a)
    def hit(k):
        return a[k] != b[k] and mine(base + k)
    while i < n:
        if not hit(i):
            i += 1
            continue
        j = last = i
        while j < n and j - last < 4:
            if hit(j):
                last = j
            elif a[j] != b[j]:
                break                          # another mod's byte: end the run here
            j += 1
        out.append((base + i, a[i:last + 1], b[i:last + 1]))
        i = last + 1
    return out


def owners_of_changes(a: bytes, b: bytes, base: int, claims):
    """{address: owner} for every changed byte, from the applied registry claims (cave,
    detour, patch: (addr, size, owner)). A changed byte no claim covers aborts, as in
    verify.py."""
    out = {}
    for k in range(len(a)):
        if a[k] != b[k]:
            va = base + k
            who = next((o for lo, n, o in claims if lo <= va < lo + n), None)
            if who is None:
                raise SystemExit(f"0x{va:08x} changed but no applied claim covers it")
            out[va] = who
    return out


def elek_source(mod, dst):
    """The stub as elekloader assembles it: every section it names becomes .run (code and
    initialised data, copied to the area at boot), .bss stays .bss. Also assembled here with
    -mcpu=5475 into build/obj/<id>.elf (relocatable), for verify.py's frame check and to keep
    the stub valid for a cave build."""
    import re
    src = (mod["_dir"] / mod["_sources"]["stub"]).read_text()
    out = []
    for line in src.splitlines():
        m = re.match(r"^(\s*)(\.text\b.*|\.data\b.*|\.section\s+(\.[\w.]+).*)$", line)
        if m and not (m.group(3) or "").startswith(".bss") and not line.strip().startswith(".bss"):
            line = m.group(1) + '.section .run, "ax"'
        out.append(line)
    dst.write_text("\n".join(out) + "\n")
    objdir = BUILD / "obj"
    objdir.mkdir(parents=True, exist_ok=True)
    defs = [x for k, v in sorted(mod["_params"].items()) for x in ("--defsym", f"P_{k.upper()}={int(v)}")]
    run(["m68k-elf-as", "-mcpu=5475", "-I", BUILD, "-I", ROOT, *defs, "-o",
         objdir / f"{mod['id']}.elf", mod["_dir"] / mod["_sources"]["stub"]])


def elek_build(img, stock_img, mods, enabled, elek_detours, tag, meta, syx_out, reg_claims,
               elek_patches):
    """Hand the patched image to elekloader: every byte build.py changed becomes a site
    of one format-2 mod ("rytm-mods", its stock bytes pinned by sha256 again), the area =
    "elek" mods' sources its code, their elek detours `jmp` sites; elekloader links that
    code into its DDR area with its core (core-ar2), appends the boot copier, repacks and
    verifies. Returns the manifest's "elek" record, plus "_mainos" (the depacked MAIN OS)."""
    rev, ddr = elek_pinning(meta)
    base = meta["base"]
    core = mods[ELEK_MOD].get("_elek", {}).get("core", "core-ar2")
    work = BUILD / "elek" / tag
    shutil.rmtree(work, ignore_errors=True)
    work.mkdir(parents=True)
    env = dict(os.environ, ELEKLOADER_CROSS=ELEK_CROSS)
    py = sys.executable

    def elek(*args):
        return run([py, "-m", *args], cwd=ELEK_DIR, env=env)

    elek("elekloader.sdk.build", ELEK_DIR / "mods" / core, "--stock", STOCK_SYX,
         "--out", work / "core")
    core_mod = next((work / "core").glob("*.elemod"))

    # one format-2 mod per rytm-mods mod, so each is an ordinary elekloader module that
    # combines with anyone else's for the Rytm under elekloader's own checks: its sites are
    # the bytes its registry claims changed (each pinned again by elekloader through the
    # stock bytes' sha256); an area = "elek" mod adds its sources, subscriptions and its
    # elek detours (jmp sites elekloader resolves)
    owner_of = owners_of_changes(stock_img, bytes(img), base, reg_claims)
    elek_mods = sorted(m for m in enabled if mods[m].get("area") == "elek")
    shutil.copy(BUILD / "symbols.inc", work / "symbols.inc")
    built, nsites = [], 0
    for mid in sorted(set(owner_of.values()) | set(elek_mods)):
        mdir = work / "mods" / mid
        mdir.mkdir(parents=True)
        sites = [{"addr": f"0x{a:08x}", "stock": st.hex(), "op": "bytes", "new": nw.hex()}
                 for a, st, nw in change_runs(stock_img, bytes(img), base,
                                              lambda va: owner_of.get(va) == mid)]
        sources, subscribe = [], []
        if mid in elek_mods:
            elek_source(mods[mid], mdir / "stub.s")
            shutil.copy(work / "symbols.inc", mdir / "symbols.inc")
            if (BUILD / "shared.inc").exists():
                shutil.copy(BUILD / "shared.inc", mdir / "shared.inc")
            sources = ["stub.s"]
            subscribe = mods[mid].get("_elek", {}).get("subscribe", [])
            for d in elek_detours:
                if d["owner"] == mid:
                    # elek_size: a jmp whose 6 bytes end mid-instruction covers the whole
                    # displaced span (elekloader pads it with nops, never run: the stub rejoins)
                    n = d.get("elek_size", 6)
                    st = stock_img[d["addr"] - base:d["addr"] - base + n]
                    sites.append({"addr": f"0x{d['addr']:08x}", "stock": st.hex(),
                                  "op": "jmp", "target": d["entry"]})
            for q in elek_patches:
                if q["owner"] == mid:
                    sites.append({"addr": f"0x{q['addr']:08x}", "stock": q["expect"],
                                  "op": "ptr", "target": q["from_symbol"]})
        requires = (["core"] if mid in elek_mods else []) + \
            [ELEK_ID + p for p in sorted(enabled) if mods[p].get("_provides") and
             mods[mid].get("_needs_shared") and p != mid]
        modjson = {"id": ELEK_ID + mid, "version": tag, "title": mods[mid]["title"],
                   "category": "rytm-mods", "author": "rytm-mods",
                   "license": "NOASSERTION",
                   "description": (mods[mid].get("summary") or "").strip()[:1000],
                   "device": "analog-rytm-mk2", "os": "1.73", "requires": requires,
                   "sources": sources, "subscribe": subscribe, "sites": sites,
                   "defsym": {f"P_{k.upper()}": int(v) for k, v in mods[mid]["_params"].items()}
                   if mid in elek_mods else {}}
        (mdir / "mod.json").write_text(json.dumps(modjson, indent=1) + "\n")
        elek("elekloader.sdk.build", mdir, "--stock", STOCK_SYX, "--out", mdir / "out")
        built.append(next((mdir / "out").glob("*.elemod")))
        nsites += len(sites)
    version = STOCK_SYX.read_bytes()[0x3b:0x3f].decode()   # the stock container's "1.73"
    log = elek("elekloader.patch", "--stock", STOCK_SYX, "--mod", core_mod,
               *[x for b in built for x in ("--mod", b)], "--out", syx_out, "--version", version)
    man = json.loads(Path(str(syx_out) + ".json").read_text())
    smap = {k: int(v, 16) for k, v in
            json.loads(Path(str(syx_out) + ".map.json").read_text()).items()}
    # the depacked MAIN OS, through our own tool (verify.py round-trips it again)
    ext = work / "extract"
    ext.mkdir()
    run([EFT, "-i", syx_out, "-o", ext])
    mainos = (ext / f"section_{MAINOS_SECTION}_MAIN_OS.bin").read_bytes()
    if sha256(mainos) != man["main_sha256"]:
        raise SystemExit("elekloader's main OS and the extracted one differ")
    lay = man["link"]["layout"]
    detours = []
    for d in elek_detours:
        target = smap.get(f"{ELEK_ID}{d['owner']}:{d['entry']}")
        if target is None or not (ddr[0] <= target < ddr[1]):
            raise SystemExit(f"{d['owner']}: {d['entry']} not placed in the area ({target})")
        rejoin = d.get("rejoin", d["addr"] + len(bytes.fromhex(d["expect"])))
        detours.append({"mod": d["owner"], "addr": d["addr"], "entry": d["entry"],
                        "target": target, "displaced": d["expect"], "rejoin": rejoin,
                        "reemit": d.get("reemit", True), "elek": True})
    patches = []
    for q in elek_patches:
        target = smap.get(f"{ELEK_ID}{q['owner']}:{q['from_symbol']}")
        if target is None or not (ddr[0] <= target < ddr[1]):
            raise SystemExit(f"{q['owner']}: {q['from_symbol']} not placed in the area ({target})")
        patches.append({"mod": q["owner"], "addr": q["addr"], "symbol": q["from_symbol"],
                        "expect": q["expect"], "target": target})
    print("  elekloader:", " | ".join(l.strip() for l in log.splitlines()
                                      if l.startswith(("linked", "verified", "WROTE"))))
    return {"rev": rev, "core": core, "core_elemod_sha256": sha256(core_mod.read_bytes()),
            "elemods": {b.name: sha256(b.read_bytes()) for b in built}, "sites": nsites,
            "version": version, "layout": lay, "area": list(ddr),
            "mods": elek_mods, "detours": detours, "patches": patches,
            "symbols": {k: v for k, v in smap.items()
                        if k.startswith((ELEK_ID, "core:"))},
            "output": {k: man["output"][k] for k in ("flash_end", "flash_headroom")
                       if k in man["output"]},
            "inplace_min_gap": man["output"].get("main", {}).get("inplace_min_gap"),
            "_mainos": mainos}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mods", nargs="*", default=None,
                    help="build only these mod ids (for hardware bisection)")
    ap.add_argument("--tag", default=None, help="output name suffix")
    ap.add_argument("--area-elek", action="append", default=[], metavar="MOD",
                    help="link this mod's code into elekloader's DDR area instead of its caves "
                         "(needs 0027-elekloader; mods/0027-elekloader/design.md)")
    ap.add_argument("--param", action="append", default=[], metavar="MOD:KEY=VAL",
                    help="override a mod param for an ablation build; KEY=VAL without MOD: "
                         "sets a linked param (linked_params) on every mod that lists it")
    args = ap.parse_args()

    BUILD.mkdir(exist_ok=True)
    syms = symmod.load(ROOT / "re" / "symbols.toml")
    meta = syms["meta"]
    base = meta["base"]
    reg = layout.load(ROOT / "registry" / "allocations.toml")

    check_stock()
    ensure_tool()
    img = bytearray(extract_sections(meta))
    # Kept pristine so a claim in a dead-code pool can be checked against the stock
    # bytes it was analysed on, rather than against zero: those pools hold routines,
    # not padding, so "is it all zeros" is the wrong question there.
    stock_img = bytes(img)
    layout.resolve_expect(reg, stock_img, base)   # the registry's expects, from this image (tools/hash_expect.py)

    reg_pools = reg.get("pool", [])

    def pool_for(c):
        """The pool a claim sits wholly inside, or None. layout.py already proved one
        exists for every claim, so None here only happens for a claim table with no
        pool of its own."""
        lo, hi = c["addr"], c["addr"] + c["size"]
        return next((p for p in reg_pools
                     if p["start"] <= lo and hi <= p["end"]), None)
    original_len = len(img)

    mods = load_mods(set(args.mods) if args.mods is not None else None)
    enabled = {i for i, m in mods.items() if m.get("enabled")}

    # Ablation overrides. Applied after defaults so the manifest records exactly what was
    # assembled, and unknown mods/keys abort rather than silently building the default.
    overrides: dict[str, dict[str, int]] = {}
    for spec in args.param:
        if ":" not in spec and "=" in spec:   # a linked param: every mod that lists it
            key, val = spec.split("=", 1)
            owners = [m for m in mods if key in mods[m].get("linked_params", [])]
            if not owners:
                raise SystemExit(f"--param {spec!r}: no mod lists {key!r} in linked_params")
            for who in owners:
                mods[who]["_params"][key] = int(val, 0)
                overrides.setdefault(who, {})[key] = int(val, 0)
            continue
        try:
            who, kv = spec.split(":", 1)
            key, val = kv.split("=", 1)
        except ValueError:
            raise SystemExit(f"--param must be MOD:KEY=VAL or KEY=VAL, got {spec!r}")
        if who not in mods:
            raise SystemExit(f"--param names unknown mod {who!r}")
        if key not in mods[who]["_params"]:
            known = ", ".join(sorted(mods[who]["_params"])) or "(none)"
            raise SystemExit(f"--param: {who} has no param {key!r}. Known: {known}")
        mods[who]["_params"][key] = int(val, 0)
        overrides.setdefault(who, {})[key] = int(val, 0)

    for mid in args.area_elek:
        if mid not in enabled:
            raise SystemExit(f"--area-elek {mid}: not in the build")
        mods[mid]["area"] = "elek"
    excludes = layout.load_excludes(ROOT)
    check_excludes(enabled, excludes)
    check_param_excludes(mods, enabled)
    check_linked_params(mods, enabled)
    for mid in sorted(enabled):   # a mod's known limitation in this tree ([mod] warning), shown with every build of it
        if mods[mid].get("warning"):
            print(f"WARNING: {mid}: {mods[mid]['warning']}")
    problems = layout.validate(reg, enabled,
                               {m: d["_params"] for m, d in mods.items()},
                               excludes)
    if problems:
        for p in problems:
            print("ERROR:", p)
        raise SystemExit(1)

    symmod.emit_inc(syms, BUILD / "symbols.inc")

    caves = {}
    for c in reg.get("cave", []):
        caves.setdefault(c["owner"], []).append(c)
    stub_symbols: dict[str, dict[str, int]] = {}
    applied = []

    # Providers assemble first: their symbols become build/shared.inc, which the
    # stubs that call into them include. Claim addresses are fixed in the registry,
    # so one pass is enough - nothing here depends on a provider's own size.
    providers = sorted(m for m in enabled if mods[m].get("_provides"))
    needs = sorted(m for m in enabled if mods[m].get("_needs_shared"))
    if needs and not providers:
        raise SystemExit(
            f"{', '.join(needs)} require the shared runtime, but no enabled mod "
            f"provides it - enable the provider or disable them"
        )

    for mid in sorted(enabled, key=lambda m: (not mods[m].get("_provides"), m)):
        mod = mods[mid]
        if mod.get("area") == "elek":
            # linked by elekloader into its DDR area (elek_build), not into a cave
            stub_symbols[mid] = {}
            continue
        if not mod["_sources"].get("stub"):
            # a patch-only mod (raw byte edits, no code cave) - nothing to assemble
            stub_symbols[mid] = {}
            continue
        claim = [c for c in caves.get(mid, [])
                 if not layout.gated_out(c.get("gate"), mod["_params"], mid)]
        if not caves.get(mid):
            raise SystemExit(f"{mid} is enabled but has no cave claim in the registry")
        if not claim:
            stub_symbols[mid] = {}
            continue
        sections, stub_syms = assemble(mod, claim, mod["_params"])
        stub_symbols[mid] = stub_syms
        if mod.get("_provides"):
            emit_shared_inc(stub_syms, mid)
        for c in claim:
            name = c.get("section", ".text")
            code = sections[name]
            if len(code) > c["size"]:
                raise SystemExit(
                    f"{mid}: {name} is {len(code)} B but its cave claim at "
                    f"0x{c['addr']:08x} reserves {c['size']} B - widen the claim in "
                    f"registry/allocations.toml"
                )
            off = c["addr"] - base
            region = img[off:off + c["size"]]
            home = pool_for(c)
            if home is not None and home.get("stock") == "code":
                # A dead-code pool holds a routine nothing calls, so it is not zeros.
                # Two things are checked instead: the pool still holds the exact bytes
                # the reachability analysis was run on, and nothing has already been
                # written into this claim.
                lo, hi = home["start"] - base, home["end"] - base
                got = hashlib.sha256(stock_img[lo:hi]).hexdigest()
                want = home.get("expect_sha256")
                if want is None:
                    raise SystemExit(
                        f"pool {home['name']} is stock = \"code\" but has no "
                        f"expect_sha256; a dead-code pool has to name the bytes it was "
                        f"analysed on, or the claim is not guarded at all"
                    )
                if got != want:
                    raise SystemExit(
                        f"{mid}: pool {home['name']} does not hold the bytes it was "
                        f"analysed on - sha256 {got}, expected {want}. The pool is not "
                        f"the dead routine cavescan reported; re-run the analysis "
                        f"before putting anything here"
                    )
                if region != stock_img[off:off + c["size"]]:
                    raise SystemExit(
                        f"{mid}: cave at 0x{c['addr']:08x} in {home['name']} has "
                        f"already been written by an earlier claim"
                    )
            elif any(region):
                raise SystemExit(
                    f"{mid}: cave at 0x{c['addr']:08x} is not free - "
                    f"{sum(1 for b in region if b)} non-zero byte(s) already there"
                )
            img[off:off + len(code)] = code
            applied.append({"mod": mid, "stub_addr": c["addr"],
                            "stub_size": len(code), "section": name})

    detours_applied = []
    elek_detours, elek_patches = [], []
    for det in sorted(reg.get("detour", []), key=lambda d: d.get("chain_pos", 0)):
        if det["owner"] not in enabled:
            continue
        if layout.gated_out(det.get("gate"), mods[det["owner"]]["_params"], det["owner"]):
            continue
        off = det["addr"] - base
        # expect covers the full displaced span the stub re-emits; verify all of it,
        # even though only the first `size` bytes are overwritten by the jmp.
        want = bytes.fromhex(det["expect"])
        got = bytes(img[off:off + len(want)])
        if got != want:
            raise SystemExit(
                f"{det['owner']}: detour host 0x{det['addr']:08x} holds {got.hex()}, "
                f"expected {want.hex()} - the address is wrong, the image is not stock, "
                f"or another mod already patched here"
            )
        entry = det["entry"]
        if det.get("elek") or mods[det["owner"]].get("area") == "elek":
            # its entry is in elekloader's area: elek_build hands it over as a jmp site
            if mods[det["owner"]].get("area") != "elek":
                raise SystemExit(f"{det['owner']}: detour 0x{det['addr']:08x} says elek = true "
                                 f"but the mod is not area = \"elek\"")
            elek_detours.append(det)
            continue
        stub_syms = stub_symbols[det["owner"]]
        if entry not in stub_syms:
            raise SystemExit(
                f"{det['owner']}: detour at 0x{det['addr']:08x} names entry {entry!r}, "
                f"which the linked stub does not define. "
                f"Known: {', '.join(sorted(stub_syms)) or '(none)'}"
            )
        target = stub_syms[entry]
        if target % 2:
            raise SystemExit(
                f"{det['owner']}: entry {entry!r} resolved to 0x{target:08x}, an ODD "
                f"address. A detour installs `jmp <target>`, and an odd instruction "
                f"address is an ADDRESS ERROR on ColdFire (VEC 03) the first time the host "
                f"runs. Add `.align 2` before the label, and keep byte-sized state after "
                f"every entry point rather than between them."
            )
        owned = caves[det["owner"]]
        if not any(c["addr"] <= target < c["addr"] + c["size"] for c in owned):
            raise SystemExit(
                f"{det['owner']}: entry {entry!r} resolved to 0x{target:08x}, outside its "
                f"cave claims " + ", ".join(f"0x{c['addr']:08x}+0x{c['size']:x}"
                                            for c in owned)
            )
        img[off:off + 6] = b"\x4e\xf9" + target.to_bytes(4, "big")
        rejoin = det.get("rejoin")
        if rejoin is None:
            # where stock resumes: right past the instructions the stub re-emits
            rejoin = det["addr"] + len(want)
        elif rejoin != "none" and not isinstance(rejoin, int):
            raise SystemExit(
                f"{det['owner']}: detour at 0x{det['addr']:08x} has rejoin {rejoin!r}; "
                f"it must be an address or \"none\""
            )
        detours_applied.append(
            {"mod": det["owner"], "addr": det["addr"], "entry": entry,
             "target": target, "displaced": want.hex(), "rejoin": rejoin,
             "reemit": det.get("reemit", True)}
        )

    patches_applied = []
    for q in reg.get("patch", []):
        if q["owner"] not in enabled:
            continue
        if layout.gated_out(q.get("gate"), mods[q["owner"]]["_params"], q["owner"]):
            continue
        off = q["addr"] - base
        want = bytes.fromhex(q["expect"])
        if q.get("foreign"):
            # written by elekloader (its core's sites); here only checked to be stock
            if bytes(img[off:off + len(want)]) != want:
                raise SystemExit(f"{q['owner']}: foreign site 0x{q['addr']:08x} is not stock "
                                 f"({bytes(img[off:off + len(want)]).hex()}) - a collision")
            continue
        if "from_symbol" in q and mods[q["owner"]].get("area") == "elek":
            # a pointer to a label elekloader places: handed over as a `ptr` site
            if bytes(img[off:off + len(want)]) != want:
                raise SystemExit(f"{q['owner']}: patch site 0x{q['addr']:08x} is not stock")
            elek_patches.append(q)
            continue
        if "from_symbol" in q:
            stub_syms = stub_symbols.get(q["owner"], {})
            if q["from_symbol"] not in stub_syms:
                raise SystemExit(f"{q['owner']}: no symbol `{q['from_symbol']}` in its stub")
            repl = stub_syms[q["from_symbol"]].to_bytes(4, "big")
        else:
            repl = bytes.fromhex(q["replace"])
        got = bytes(img[off:off + len(want)])
        if got != want:
            raise SystemExit(
                f"{q['owner']}: patch site 0x{q['addr']:08x} holds {got.hex()}, "
                f"expected {want.hex()} - wrong address, non-stock image, or a collision"
            )
        img[off:off + len(repl)] = repl
        patches_applied.append({"mod": q["owner"], "addr": q["addr"],
                                "expect": want.hex(), "replace": repl.hex()})

    if len(img) != original_len:
        raise SystemExit(f"image size changed: {original_len} -> {len(img)}")

    tag = args.tag or ("_".join(m.split("-", 1)[0] for m in sorted(enabled)) or "stock")
    if overrides and not args.tag:
        # keep ablation outputs from colliding with the default build's filenames
        tag += "_" + "_".join(f"{k}{v}" for m in sorted(overrides)
                              for k, v in sorted(overrides[m].items()))
    mainos_out = BUILD / f"mainos_{tag}.bin"
    syx_out = BUILD / f"Analog-Rytm_MKII_{meta['target']}_{tag}.syx"
    elek = None
    if ELEK_MOD in enabled:
        claims = [(a["stub_addr"], a["stub_size"], a["mod"]) for a in applied] + \
                 [(d["addr"], 6, d["mod"]) for d in detours_applied] + \
                 [(q["addr"], len(q["replace"]) // 2, q["mod"]) for q in patches_applied]
        elek = elek_build(img, stock_img, mods, enabled, elek_detours, tag, meta, syx_out, claims,
                          elek_patches)
        detours_applied += elek["detours"]
        img = bytearray(elek.pop("_mainos"))   # stock length + the appended .boot and blob
    else:
        for mid in sorted(enabled):
            if mods[mid].get("area") == "elek":
                raise SystemExit(f"{mid} is area = \"elek\": it needs {ELEK_MOD} in the image")
        if elek_detours:
            raise SystemExit("elek detours without " + ELEK_MOD)
        mainos_out.write_bytes(img)
        run([EFT, "-i", STOCK_SYX, "-c", str(MAINOS_SECTION), mainos_out, "-o", syx_out])
    mainos_out.write_bytes(img)

    manifest = {
        "target": meta["target"],
        "stock_mainos_sha256": meta["mainos_sha256"],
        "patched_mainos_sha256": sha256(bytes(img)),
        "patched_mainos_size": len(img),
        "syx": syx_out.name,
        "syx_sha256": sha256(syx_out.read_bytes()),
        "mods": [
            {**a, "status": mods[a["mod"]]["status"], "title": mods[a["mod"]]["title"]}
            for a in applied
        ],
        "detours": detours_applied,
        "patches": patches_applied,
        "params": {m: mods[m]["_params"] for m in sorted(enabled) if mods[m]["_params"]},
        "enabled": sorted(enabled),
    }
    if elek:
        manifest["elek"] = elek
    (BUILD / f"manifest_{tag}.json").write_text(json.dumps(manifest, indent=2) + "\n")

    print(f"built {syx_out.relative_to(ROOT)} ({syx_out.stat().st_size:,} B)")
    print(f"  MIDI upgrade (Transfer, or STARTUP menu TRIG 4) -> {syx_out.name}")
    for a in applied:
        print(f"  {a['mod']}: stub 0x{a['stub_addr']:08x} ({a['stub_size']} B) "
              f"[{mods[a['mod']]['status']}]")
        prm = mods[a["mod"]]["_params"]
        if prm:
            marks = " ".join(f"{k}={v}" + ("*" if k in overrides.get(a["mod"], {}) else "")
                             for k, v in sorted(prm.items()))
            print(f"      params {marks}")
        for d in detours_applied:
            if d["mod"] == a["mod"]:
                print(f"      detour 0x{d['addr']:08x} -> {d['entry']} @ 0x{d['target']:08x}")
    for q in patches_applied:
        print(f"  {q['mod']}: patch 0x{q['addr']:08x} {q['expect']} -> {q['replace']}")
    print(f"  MAIN OS {len(img)} B, sha256 {manifest['patched_mainos_sha256'][:16]}...")


if __name__ == "__main__":
    main()
