#!/usr/bin/env python3
"""Build patched Analog Rytm MKII firmware from stock + the enabled mods.

Every build starts from the pinned stock image and asserts its way forward:
stock checksum, extracted MAIN OS checksum and size, registry layout, the cave
target actually being free, and each detour host still holding its expected
stock bytes. Any mismatch aborts rather than producing a plausible-looking image.

Only MAIN OS (section 3) is ever rewritten. The bootstrap (section 2) is the
recovery path that survives a bad MAIN OS - see docs/HAZARDS.md - and this tool
checks that it comes back out of the rebuilt file unchanged.
"""

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import layout
import symbols as symmod

ROOT = Path(__file__).resolve().parent.parent
BUILD = ROOT / "build"
STOCK_SYX = ROOT / "stock" / "Analog-Rytm_MKII_OS1.73.syx"
EFT_DIR = ROOT / "vendor" / "elektron-firmware-tool"
EFT = EFT_DIR / "elektron-firmware-tool"

MAINOS_SECTION = 3
BOOTSTRAP_SECTION = 2


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def run(cmd, **kw):
    proc = subprocess.run(cmd, capture_output=True, text=True, **kw)
    if proc.returncode != 0:
        raise SystemExit(f"command failed: {' '.join(map(str, cmd))}\n{proc.stdout}{proc.stderr}")
    return proc.stdout


def check_stock():
    sums = (ROOT / "stock" / "SHA256SUMS").read_text().split()
    want = dict(zip(sums[1::2], sums[0::2]))
    for name, expect in want.items():
        got = sha256((ROOT / "stock" / name).read_bytes())
        if got != expect:
            raise SystemExit(f"stock/{name} checksum mismatch\n  want {expect}\n  got  {got}")


def ensure_tool():
    if not EFT.exists():
        run(["make"], cwd=EFT_DIR)
    if not EFT.exists():
        raise SystemExit(f"{EFT} missing; run `git submodule update --init` then `make` there")


def extract_sections(meta) -> bytes:
    """Unpack stock once into build/extract; return the stock MAIN OS."""
    cache = BUILD / "stock_mainos.bin"
    boot = BUILD / "stock_bootstrap.bin"
    if not (cache.exists() and boot.exists()):
        tmp = BUILD / "extract"
        shutil.rmtree(tmp, ignore_errors=True)
        tmp.mkdir(parents=True)
        run([EFT, "-i", STOCK_SYX, "-o", tmp])
        src = tmp / f"section_{MAINOS_SECTION}_MAIN_OS.bin"
        if not src.exists():
            raise SystemExit(f"extraction produced no {src.name}; got {list(tmp.iterdir())}")
        shutil.copy(src, cache)
        shutil.copy(tmp / f"section_{BOOTSTRAP_SECTION}_bootstrap.bin", boot)
    data = cache.read_bytes()
    if len(data) != meta["mainos_size"]:
        raise SystemExit(f"MAIN OS is {len(data)} B, expected {meta['mainos_size']}")
    if sha256(data) != meta["mainos_sha256"]:
        raise SystemExit(f"MAIN OS checksum mismatch: {sha256(data)}")
    if sha256(boot.read_bytes()) != meta["bootstrap_sha256"]:
        raise SystemExit(f"bootstrap checksum mismatch: {sha256(boot.read_bytes())}")
    return data


def load_mods(only):
    mods = {}
    for d in sorted((ROOT / "mods").iterdir()):
        f = d / "mod.toml"
        if not f.is_file():
            continue
        with open(f, "rb") as fh:
            m = tomllib.load(fh)
        mod = m["mod"]
        mod["_dir"] = d
        mod["_sources"] = m.get("sources", {})
        mod["_params"] = dict(m.get("params", {}))
        mod["_elek"] = m.get("elek", {})
        mod["_provides"] = bool(mod.get("provides_shared"))
        mod["_needs_shared"] = bool(m.get("requires", {}).get("shared"))
        if only is not None:
            mod["enabled"] = mod["id"] in only
        mods[mod["id"]] = mod
    if only:
        missing = set(only) - set(mods)
        if missing:
            raise SystemExit(f"unknown mod(s): {', '.join(sorted(missing))}")
    return mods


def emit_shared_inc(syms, owner):
    """Write build/shared.inc: the provider's `shared_*` symbols, for other stubs.

    Only the shared_ prefix is exported, so a provider can keep private labels. The
    file is regenerated every build, and a stub that includes it without the provider
    enabled fails to assemble rather than linking against a stale address.
    """
    lines = [f"| Generated by tools/build.py from {owner} - do not edit.", ""]
    for name, addr in sorted(syms.items(), key=lambda kv: kv[1]):
        if name.startswith("shared_"):
            lines.append(f"        .equ    {name}, 0x{addr:08x}")
    (BUILD / "shared.inc").write_text("\n".join(lines) + "\n")


def assemble(mod, claims, params=None):
    """Assemble and link the stub across its cave claims.

    `claims` is the mod's list of registry cave entries, each naming the section it
    holds (`.text` unless it says otherwise). The pools are separate regions of the
    image and can never merge, so a mod larger than the biggest free run has to be
    split; giving each claim a section is how the linker is told where each part
    landed, and keeps the split visible in the registry rather than implied by size.

    Returns ({section: bytes}, symbols). Detour targets are resolved from `symbols`
    rather than assumed to be the start of the block: a mod may expose several entry
    points, and a detour left pointing at a stale offset is a known way to brick the
    unit.
    """
    stub = mod["_dir"] / mod["_sources"]["stub"]
    objdir = BUILD / "obj"
    objdir.mkdir(parents=True, exist_ok=True)
    obj = objdir / f"{mod['id']}.o"
    elf = objdir / f"{mod['id']}.elf"
    defs = []
    for k, v in sorted((params or {}).items()):
        defs += ["--defsym", f"P_{k.upper()}={int(v)}"]
    # 5475 is ColdFire V4e: ISA_B plus EMAC. The stock image uses both - mvz/mvs and
    # sats.l throughout, and mac/msac/movclr in the audio path - so this is the target
    # the firmware was built for. The earlier 5407 (ISA_A, the older MAC unit) happened
    # to assemble every mod written so far, because none reached past ISA_A; it rejects
    # EMAC outright. Switching produced a byte-identical image for 0000/0002/0003/0004.
    run(["m68k-elf-as", "-mcpu=5475", "-I", BUILD, "-I", ROOT, *defs, "-o", obj, stub])
    placed = []
    for c in claims:
        placed += [f"--section-start={c.get('section', '.text')}=0x{c['addr']:08x}"]
    run(["m68k-elf-ld", "-e", "0", *placed, "-o", elf, obj])
    # Only claimed sections are copied into the image. A section the stub declares
    # but no claim places still links, at an address the linker picks, and its code
    # would then point at memory nobody reserved - found 2026-09-27, when 0010's
    # .kab linked to 0x40139c74 and the build passed.
    claimed = {c.get("section", ".text") for c in claims}
    hdr = run(["m68k-elf-objdump", "-h", elf]).splitlines()
    for i, line in enumerate(hdr):
        f = line.split()
        if len(f) >= 3 and f[0].isdigit() and int(f[2], 16) and f[1] not in claimed \
                and i + 1 < len(hdr) and "ALLOC" in hdr[i + 1]:
            raise SystemExit(f"{mod['id']}: section {f[1]} ({int(f[2], 16)} B) has no cave "
                             f"claim - add one with section = \"{f[1]}\" in "
                             f"registry/allocations.toml")
    sections = {}
    for c in claims:
        name = c.get("section", ".text")
        binf = objdir / f"{mod['id']}{name.replace('.', '_')}.bin"
        run(["m68k-elf-objcopy", "-O", "binary", "--only-section", name, elf, binf])
        sections[name] = binf.read_bytes()
    syms = {}
    for line in run(["m68k-elf-nm", elf]).splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[1].upper() in ("T", "D", "B", "A", "R"):
            syms[parts[2]] = int(parts[0], 16)
    return sections, syms


def check_excludes(enabled, excludes):
    """Refuse an image with two mods that declare each other in `excludes`.

    layout.validate skips overlaps between such pairs (they deliberately claim the same
    bytes), so without this a combination would only be caught incidentally, by a cave
    or expect collision, if at all. `excludes` is layout.load_excludes' map; it is read
    from both sides so a one-sided map still refuses.
    """
    for a in sorted(enabled):
        for b in sorted(enabled):
            if a < b and (b in excludes.get(a, ()) or a in excludes.get(b, ())):
                raise SystemExit(f"mods {a} and {b} are mutually exclusive")


def check_param_excludes(mods, enabled):
    """Refuse an image in which an enabled mod's `excludes_params` ("MOD:PARAM" in its [mod]
    table) names an enabled mod whose param is on (non-zero).

    For a combination `excludes` cannot express because it depends on a param: 0021's user
    slots take over the parameter records of 0014's FUNC. GEN. (403..405, funcgen) and of LT
    TEST and CB TEST (438, 457..460, test), so a build listing those machines would give them
    the user slots' records. Run after the --param overrides, so an ablation is checked as built.
    """
    for mid in sorted(enabled):
        for spec in mods[mid].get("excludes_params", []):
            who, _, key = spec.partition(":")
            if who in enabled and mods[who]["_params"].get(key):
                raise SystemExit(f"{mid} cannot be built with {who} {key}={mods[who]['_params'][key]} "
                                 f"(its excludes_params: {spec})")


def check_linked_params(mods, enabled):
    """Refuse an image whose enabled mods disagree on a param they all list in `linked_params`.

    One feature can span several mods: 0021's user slots need 0022's router to pass their SysEx
    (1A..1D) and 0023's 12 B mailbox (td_pool_tab, which 0021 calls - with the 8 B mailbox that
    word is 0023's code). Each mod gates its part on its own `slots`; this keeps them in step.
    A linked param set (nonzero) also needs every mod that lists it in the image: 0021 slots=1
    without 0023 would call into whatever sits at td_pool_tab's address, without 0022 its SysEx
    would never arrive.
    """
    seen: dict[str, tuple[str, int]] = {}
    for mid in sorted(enabled):
        for key in mods[mid].get("linked_params", []):
            val = mods[mid]["_params"][key]
            if key in seen and seen[key][1] != val:
                raise SystemExit(f"linked param {key}: {seen[key][0]} has {key}={seen[key][1]} but "
                                 f"{mid} has {key}={val} (pass --param {key}=N to set it on all)")
            seen.setdefault(key, (mid, val))
    for key, (mid, val) in seen.items():
        missing = sorted(m for m in mods if key in mods[m].get("linked_params", []) and m not in enabled)
        if val and missing:
            raise SystemExit(f"linked param {key}={val} ({mid}) needs {', '.join(missing)} in the image too")


