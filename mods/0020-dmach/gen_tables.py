#!/usr/bin/env python3
"""Tables for dmach.c, written to dmach_tables.h: a 257-point sine, the phase
increments of MIDI notes 108..120 at 48 kHz, and per-block decay factors."""
import math
SR, BLOCK = 48000, 32
sine = [round(32767 * math.sin(2 * math.pi * i / 256)) for i in range(257)]
incs = [round(440 * 2 ** ((n - 69) / 12) * 2**32 / SR) for n in range(108, 121)]
# 0..127 -> 4 ms .. ~8 s (exponential), as Q15 multipliers per 32-sample block
dec = []
for k in range(128):
    t = 0.004 * 2 ** (k * 11 / 127)
    dec.append(min(32767, round(32768 * math.exp(-BLOCK / (t * SR)))))
def arr(ctype, name, v, per=12):
    rows = [", ".join(str(x) for x in v[i:i + per]) for i in range(0, len(v), per)]
    return f"static const {ctype} {name}[{len(v)}] TEXT = {{\n  " + ",\n  ".join(rows) + "\n};\n"
with open("dmach_tables.h", "w") as f:
    f.write("/* Generated by gen_tables.py. */\n")
    f.write(arr("int16_t", "sine_table", sine))
    f.write(arr("uint32_t", "note_inc", incs, 4))
    f.write(arr("uint16_t", "decay_q15", dec))
